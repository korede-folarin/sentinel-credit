def cv_splitter() -> StratifiedKFold:
    return StratifiedKFold(n_splits=N_SPLITS, shuffle=True, random_state=RANDOM_SEED)


def load_data() -> pd.DataFrame:
    """Load the modelable population from the feature store.

    Raw psycopg2 connection, not SQLAlchemy — pandas 2.2's
    engine detection breaks against the SQLAlchemy<2.0 pin this
    project requires for apache-airflow==2.9.1.
    """
    password = os.environ.get("SENTINEL_DB_PASSWORD", "")
    conn = psycopg2.connect(
        host=DB["host"], port=DB["port"], dbname=DB["name"],
        user="postgres", password=password,
    )
    try:
        df = pd.read_sql(
            f"SELECT * FROM {DB['schema']}.customer_features", conn
        )
    finally:
        conn.close()
    return df[df[FILTER_COLUMN] == FILTER_VALUE].copy()


def split_data(df: pd.DataFrame, strategy: str = None) -> tuple:
    """
    Split into train/test (falls back to config['model']
    ['split_strategy'] if strategy not passed).

    'stratified': random split, preserves class balance. Tests
    generalization to unseen customers, not temporal drift.

    'temporal': out-of-time split on first_transaction_date —
    the EBA-required validation element, and the real deployment
    condition (Decision 10). Requires
    config['model']['temporal_split_date'].

    customer_id is carried separately (not a model feature) so
    evaluate_models.py can join predictions back to segment
    labels for fairness checks.
    """
    strategy = strategy or MODEL_CFG.get("split_strategy", "stratified")
    X_full = df[MODEL_FEATURES].fillna(df[MODEL_FEATURES].median(numeric_only=True))
    y_full = df[TARGET_COLUMN]
    ids_full = df["customer_id"]

    if strategy == "temporal":
        split_date = MODEL_CFG.get("temporal_split_date")
        if not split_date:
            raise ValueError(
                "split_strategy: temporal requires "
                "model.temporal_split_date in config.yaml"
            )
        split_date = pd.Timestamp(split_date)
        first_tx = pd.to_datetime(df["first_transaction_date"])

        train_mask = first_tx < split_date
        test_mask = first_tx >= split_date

        X_train, X_test = X_full[train_mask], X_full[test_mask]
        y_train, y_test = y_full[train_mask], y_full[test_mask]
        ids_train = ids_full[train_mask]
        ids_test = ids_full[test_mask]

        print(f"  Temporal split at {split_date.date()}: "
              f"{train_mask.sum():,} train / {test_mask.sum():,} test")

    else:
        X_train, X_test, y_train, y_test, ids_train, ids_test = train_test_split(
            X_full, y_full, ids_full,
            test_size=TEST_SIZE, random_state=RANDOM_SEED, stratify=y_full,
        )
        print(f"  Stratified split: {len(X_train):,} train / {len(X_test):,} test")

    return X_train, X_test, y_train, y_test, ids_train, ids_test


def gini_from_auc(auc: float) -> float:
    return 2.0 * auc - 1.0


def train_logistic_regression(X_train, y_train, X_test, y_test) -> dict:
    """Train and calibrate the Logistic Regression baseline. See Decision 4."""
    # RobustScaler, not StandardScaler: EDA found genuine long
    # right tails (income, order value) that a mean/std scaler
    # would let distort the scale for everyone.
    scaler = RobustScaler()
    X_train_s = scaler.fit_transform(X_train)
    X_test_s = scaler.transform(X_test)

    grid = PARAMS["logistic_regression"]
    # Hyperparameter search runs on the training set only via
    # cv_splitter() — the test set is never touched during selection.
    search = GridSearchCV(
        LogisticRegression(random_state=RANDOM_SEED),
        param_grid=grid,
        scoring=CV_SCORING,
        cv=cv_splitter(),
        n_jobs=-1,
    )
    search.fit(X_train_s, y_train)
    best_params = search.best_params_

    # class_weight='balanced' helps the model learn from the
    # rare positive class but distorts predict_proba's scale;
    # Platt scaling (sigmoid) recalibrates against observed
    # frequencies without affecting ranking (Gini/AUC/KS).
    base_model = LogisticRegression(random_state=RANDOM_SEED, **best_params)
    model = CalibratedClassifierCV(base_model, method="sigmoid", cv=cv_splitter())
    model.fit(X_train_s, y_train)

    proba = model.predict_proba(X_test_s)[:, 1]
    auc = roc_auc_score(y_test, proba)

    # CalibratedClassifierCV fits one estimator per CV fold
    # rather than exposing a single .coef_ — average across
    # folds for a representative coefficient set.
    fold_coefs = np.array([
        clf.estimator.coef_[0] for clf in model.calibrated_classifiers_
    ])
    coefs = dict(zip(MODEL_FEATURES, fold_coefs.mean(axis=0)))

    return {
        "name": "logistic_regression",
        "model": model,
        "scaler": scaler,
        "auc": round(auc, 4),
        "gini": round(gini_from_auc(auc), 4),
        "cv_best_score": round(search.best_score_, 4),
        "cv_best_params": search.best_params_,
        "test_proba": proba,
        "coefficients": coefs,
    }


def train_decision_tree(X_train, y_train, X_test, y_test) -> dict:
    """Train and calibrate the Decision Tree baseline. See Decision 4."""
    grid = PARAMS["decision_tree"]
    search = GridSearchCV(
        DecisionTreeClassifier(random_state=RANDOM_SEED),
        param_grid=grid,
        scoring=CV_SCORING,
        cv=cv_splitter(),
        n_jobs=-1,
    )
    search.fit(X_train, y_train)
    best_params = search.best_params_

    # Same calibration rationale as Logistic Regression above.
    base_model = DecisionTreeClassifier(random_state=RANDOM_SEED, **best_params)
    model = CalibratedClassifierCV(base_model, method="sigmoid", cv=cv_splitter())
    model.fit(X_train, y_train)

    proba = model.predict_proba(X_test)[:, 1]
    auc = roc_auc_score(y_test, proba)

    fold_importances = np.array([
        clf.estimator.feature_importances_ for clf in model.calibrated_classifiers_
    ])
    importances = dict(zip(MODEL_FEATURES, fold_importances.mean(axis=0)))
    return {
        "name": "decision_tree",
        "model": model,
        "scaler": None,
        "auc": round(auc, 4),
        "gini": round(gini_from_auc(auc), 4),
        "cv_best_score": round(search.best_score_, 4),
        "cv_best_params": search.best_params_,
        "test_proba": proba,
        "feature_importances": importances,
    }


def train_xgboost(X_train, y_train, X_test, y_test) -> dict:
    """Train and calibrate the XGBoost champion. See Decision 4, 14."""
    n_neg = int((y_train == 0).sum())
    n_pos = int((y_train == 1).sum())
    base_scale_pos_weight = n_neg / max(n_pos, 1)

    grid = dict(PARAMS["xgboost"])
    multipliers = grid.pop("scale_pos_weight_multiplier")
    grid["scale_pos_weight"] = [round(base_scale_pos_weight * m, 4) for m in multipliers]

    search = GridSearchCV(
        XGBClassifier(random_state=RANDOM_SEED, eval_metric="auc"),
        param_grid=grid,
        scoring=CV_SCORING,
        cv=cv_splitter(),
        n_jobs=-1,
    )
    search.fit(X_train, y_train)
    best_params = search.best_params_

    # Two artifacts fitted from this run: explanation_base
    # (uncalibrated, for SHAP — CalibratedClassifierCV can't be
    # explained directly) and model (calibrated, used for
    # scoring). See Decision 14.
    explanation_base = XGBClassifier(
        random_state=RANDOM_SEED, eval_metric="auc", **best_params,
    )
    explanation_base.fit(X_train, y_train)

    base_model = XGBClassifier(
        random_state=RANDOM_SEED, eval_metric="auc", **best_params,
    )
    model = CalibratedClassifierCV(base_model, method="sigmoid", cv=cv_splitter())
    model.fit(X_train, y_train)

    proba = model.predict_proba(X_test)[:, 1]
    auc = roc_auc_score(y_test, proba)

    fold_importances = np.array([
        clf.estimator.feature_importances_ for clf in model.calibrated_classifiers_
    ])
    importances = dict(zip(MODEL_FEATURES, fold_importances.mean(axis=0)))
    return {
        "name": "xgboost",
        "model": model,
        "explanation_base": explanation_base,
        "scaler": None,
        "auc": round(auc, 4),
        "gini": round(gini_from_auc(auc), 4),
        "cv_best_score": round(search.best_score_, 4),
        "cv_best_params": search.best_params_,
        "test_proba": proba,
        "feature_importances": importances,
    }


def get_git_commit() -> str:
    """Return the current short commit hash, or 'unknown' if git is unavailable."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, cwd=PROJECT_ROOT, timeout=5,
        )
        if result.returncode == 0:
            return result.stdout.strip()
    except Exception:
        pass
    return "unknown"


def log_governance_artifacts(out_dir: str) -> list:
    """Attach feature list, exclusion lists, and EDA/validation
    evidence to the MLflow run, so the reasoning behind the
    feature set travels with the result. See Decision 13."""
    logged = []

    feature_doc = {
        "model_features": list(MODEL_FEATURES),
        "n_model_features": len(MODEL_FEATURES),
        "exclusions": {
            name: list(globals().get(name, []))
            for name in (
                "MULTICOLLINEARITY_EXCLUDED",
                "RESOLUTION_ADJACENT_EXCLUDED",
                "EXPOSURE_TIME_EXCLUDED",
                "EXPOSURE_TIME_SUSPECTED",
                "NON_MODEL_EXCLUDED",
                "GENERATOR_INTERNAL_EXCLUDED",
            )
            if name in globals()
        },
    }
    tmp_path = os.path.join(out_dir, "_mlflow_feature_list.json")
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump(feature_doc, f, indent=2)
    mlflow.log_artifact(tmp_path, artifact_path="feature_governance")
    os.remove(tmp_path)
    logged.append("feature_list.json")

    eda_dir = os.path.join(PROJECT_ROOT, "reports", "eda")
    for fname in ("iv_screening.csv", "vif.csv", "correlated_pairs.csv",
                  "missingness.csv", "correlation_matrix.csv",
                  "eda_metadata.json"):
        fpath = os.path.join(eda_dir, fname)
        if os.path.exists(fpath):
            mlflow.log_artifact(fpath, artifact_path="feature_governance")
            logged.append(fname)

    val_dir = os.path.join(PROJECT_ROOT, "reports", "validation")
    for fname in ("fidelity.csv", "utility.csv", "privacy.csv",
                  "validation_metadata.json"):
        fpath = os.path.join(val_dir, fname)
        if os.path.exists(fpath):
            mlflow.log_artifact(fpath, artifact_path="data_validation")
            logged.append(fname)

    return logged


def log_to_mlflow(result: dict, X_train, y_train, split_strategy: str) -> None:
    """Log one training run to MLflow — tags, params, metrics,
    model artifact, and (for the champion) governance evidence.
    See Decision 8."""
    with mlflow.start_run(run_name=f"{result['name']}_{split_strategy}"):
        mlflow.set_tags({
            "feature_set": FEATURE_SET_LABEL,
            "feature_count": str(len(MODEL_FEATURES)),
            "pipeline_stage": PIPELINE_STAGE,
            "model_version": MODEL_VERSION,
            "dataset_version": DATASET_VERSION,
            "data_end_date": str(CONFIG["data_generator"]["data_end_date"]),
            "origination_end_date": str(
                CONFIG["data_generator"]["origination_end_date"]),
            "git_commit": get_git_commit(),
            "decision_log_version": DECISION_LOG_VERSION,
            "split_strategy": split_strategy,
            "is_champion": str(result["name"] == CHAMPION_MODEL),
            "xgboost_params_source": XGB_PARAMS_SOURCE,
        })

        mlflow.log_param("model_type", result["name"])
        mlflow.log_param("n_features", len(MODEL_FEATURES))
        mlflow.log_param("n_train", len(X_train))
        mlflow.log_param("train_bad_rate", round(float(y_train.mean()), 4))
        mlflow.log_param("random_seed", RANDOM_SEED)
        mlflow.log_param("split_strategy", split_strategy)
        mlflow.log_param("cv_n_splits", N_SPLITS)
        mlflow.log_param("cv_scoring", CV_SCORING)
        mlflow.log_param("business_cutoff", BUSINESS_CUTOFF)

        # Logs what GridSearchCV actually selected, not the
        # static grid — the audit trail is grid (params.yaml,
        # in git) vs chosen (here, per run).
        for k, v in result["cv_best_params"].items():
            mlflow.log_param(f"best_{k}", v)

        mlflow.log_metric("cv_score", result["cv_best_score"])
        mlflow.log_metric("gini", result["gini"])
        mlflow.log_metric("auc", result["auc"])
        # cv_score is average_precision (PR-AUC); auc is
        # ROC-AUC. Different scales — logged separately, not as
        # a derived gap.

        mlflow.sklearn.log_model(result["model"], "model")

        if result["name"] == CHAMPION_MODEL:
            logged = log_governance_artifacts(
                ARTIFACTS_DIR)
            mlflow.log_param("n_governance_artifacts", len(logged))


def save_model_package(
    results, X_train, y_train, X_test, y_test,
    ids_train, ids_test, strategy, out_dir,
) -> None:
    """Persist the governed champion package: calibrated model,
    uncalibrated explanation_base (Decision 14), feature list,
    and split IDs, so downstream scripts load rather than
    retrain and silently drift."""
    champion = next(
        (r for r in results if r["name"] == CHAMPION_MODEL), None
    )
    if champion is None:
        print(f"  No {CHAMPION_MODEL} result to persist, skipping package.")
        return

    joblib.dump(
        champion["model"],
        os.path.join(out_dir, "champion_calibrated.joblib"),
    )

    # explanation_base is currently only produced by
    # train_xgboost(). If CHAMPION_MODEL is changed to a
    # non-XGBoost model, either add an equivalent artifact to
    # that model's train_*() function, or update
    # explain_models.py to handle its absence — don't assume
    # it exists.
    has_explanation_base = "explanation_base" in champion
    if has_explanation_base:
        joblib.dump(
            champion["explanation_base"],
            os.path.join(out_dir, "champion_explanation_base.joblib"),
        )
    else:
        print(
            f"  WARNING: {CHAMPION_MODEL} has no explanation_base artifact. "
            "SHAP explainability (explain_models.py) will not run against "
            "this champion until one is added."
        )

    with open(os.path.join(out_dir, "feature_list.json"), "w", encoding="utf-8") as f:
        json.dump({"features": MODEL_FEATURES, "n_features": len(MODEL_FEATURES)},
                  f, indent=2)

    # Split IDs saved so downstream scripts reconstruct this
    # exact partition rather than re-splitting and hoping it matches.
    pd.DataFrame({"customer_id": ids_train.values}).to_csv(
        os.path.join(out_dir, "split_ids_train.csv"), index=False)
    pd.DataFrame({"customer_id": ids_test.values}).to_csv(
        os.path.join(out_dir, "split_ids_test.csv"), index=False)

    metadata = {
        "model_name": CHAMPION_MODEL,
        "model_version": MODEL_VERSION,
        "trained_at": datetime.now().isoformat(timespec="seconds"),
        "best_params": champion["cv_best_params"],
        "random_seed": RANDOM_SEED,
        "split_type": strategy,
        "test_size": TEST_SIZE,
        "n_features": len(MODEL_FEATURES),
        "feature_list": MODEL_FEATURES,
        "n_train": int(len(X_train)),
        "n_test": int(len(X_test)),
        "train_bad_rate": round(float(y_train.mean()), 4),
        "test_bad_rate": round(float(y_test.mean()), 4),

        # Lets a downstream script verify it's reading a model
        # trained on the data currently in the feature store,
        # not a stale artifact — a matching feature list alone
        # does not prove matching data.
        "dataset": {
            "dataset_version": DATASET_VERSION,
            "pipeline_stage": PIPELINE_STAGE,
            "data_end_date": str(CONFIG["data_generator"]["data_end_date"]),
            "origination_end_date": str(
                CONFIG["data_generator"]["origination_end_date"]),
            "n_modelable": int(len(X_train) + len(X_test)),
            "population_bad_rate": round(
                float((y_train.sum() + y_test.sum())
                      / (len(y_train) + len(y_test))), 6),
            "git_commit": get_git_commit(),
            "decision_log_version": DECISION_LOG_VERSION,
            "feature_set_label": FEATURE_SET_LABEL,
        },

        "calibration_method": "sigmoid",
        "xgboost_params_source": XGB_PARAMS_SOURCE,
        "cv_n_splits": N_SPLITS,
        "cv_scoring": CV_SCORING,
        "test_gini": champion["gini"],
        "test_auc": champion["auc"],
        "decision_model_artifact": "champion_calibrated.joblib",
        "explanation_model_artifact": (
            "champion_explanation_base.joblib" if has_explanation_base else None
        ),
        # This note is the artifact contract consumed by
        # explain_models.py and any auditor reading the JSON
        # directly — kept in full even though the surrounding
        # code comments above are shortened.
        "artifact_note": (
            "SHAP explains champion_explanation_base.joblib, the "
            "uncalibrated model fitted in this same run. It does not "
            "explain the calibrated probability that drives the decision. "
            "Global rankings stay directionally consistent since "
            "calibration is monotonic; local magnitudes must not be "
            "described as changes to the calibrated PD."
        ) if has_explanation_base else (
            "No explanation_base artifact was produced for this champion. "
            "SHAP explainability is unavailable until one is added."
        ),
    }
    with open(os.path.join(out_dir, "champion_metadata.json"), "w",
              encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)

    print(f"\n  Champion package saved ({MODEL_VERSION}):")
    print("    champion_calibrated.joblib        (decision model)")
    if has_explanation_base:
        print("    champion_explanation_base.joblib  (for SHAP)")
    print("    champion_metadata.json, feature_list.json")
    print("    split_ids_train.csv, split_ids_test.csv")


def print_summary(results: list) -> None:
    print("\n" + "=" * 58)
    print("BASELINE MODEL COMPARISON")
    print("=" * 58)
    print(f"{'Model':<22} {'CV ' + CV_SCORING:>16} {'Test Gini':>10} {'Test AUC':>9}")
    print("-" * 58)
    for r in sorted(results, key=lambda x: x["gini"], reverse=True):
        print(f"{r['name']:<22} {r['cv_best_score']:>16.4f} "
              f"{r['gini']:>10.4f} {r['auc']:>9.4f}")
    print("-" * 58)
    for r in results:
        print(f"{r['name']}: best params {r['cv_best_params']}")
    print("-" * 58)
    print("Full metric suite (KS, calibration, bad-rate-at-cutoff,")
    print("fairness parity) computed in evaluate_models.py")
    print("=" * 58)


def print_split_comparison(all_results: dict) -> None:
    """Print stratified vs temporal Gini per model. A large gap
    (stratified > temporal) flags weak temporal generalization —
    the concept-drift risk Decision 5's monitoring exists for."""
    print("\n" + "=" * 58)
    print("STRATIFIED vs TEMPORAL — Gini comparison")
    print("=" * 58)
    print(f"{'Model':<22} {'Stratified':>12} {'Temporal':>10} {'Gap':>8}")
    print("-" * 58)

    strat = {r["name"]: r["gini"] for r in all_results.get("stratified", [])}
    temp = {r["name"]: r["gini"] for r in all_results.get("temporal", [])}

    for name in strat.keys() | temp.keys():
        s = strat.get(name)
        t = temp.get(name)
        gap = round(s - t, 4) if (s is not None and t is not None) else None
        s_str = f"{s:.4f}" if s is not None else "n/a"
        t_str = f"{t:.4f}" if t is not None else "n/a"
        gap_str = f"{gap:+.4f}" if gap is not None else "n/a"
        flag = "  <- check drift" if gap is not None and gap > 0.05 else ""
        print(f"{name:<22} {s_str:>12} {t_str:>10} {gap_str:>8}{flag}")

    print("-" * 58)
    print("Large positive gap (stratified > temporal) suggests the")
    print("model relies on patterns that don't hold up over time —")
    print("worth investigating before deployment, not after.")
    print("=" * 58)


def pin_xgboost_params(metadata_path: str) -> dict:
    """
    Replaces the XGBoost search grid with the single configuration
    stored in a champion_metadata.json. Used when a change must be
    attributable to something other than hyperparameters, e.g. a
    feature removed for validity with the champion's settings held
    fixed (Decision 27). LR and DT are still searched: they are
    comparators, not the champion.
    """
    with open(metadata_path, "r", encoding="utf-8") as f:
        best = json.load(f)["best_params"]
    PARAMS["xgboost"] = {
        "max_depth": [best["max_depth"]],
        "n_estimators": [best["n_estimators"]],
        "learning_rate": [best["learning_rate"]],
        # scale_pos_weight is recomputed from the training data, as in
        # an unpinned run; the multiplier stays at the true class ratio.
        "scale_pos_weight_multiplier": [1.0],
    }
    return best


def refuse_foreign_package(out_dir: str) -> None:
    """
    Training overwrites the package in out_dir. Refuse if that
    package belongs to a different champion identity, so a retrain
    cannot silently replace another model's governed artifacts
    (audit A25). Re-running the SAME identity is allowed.
    """
    path = os.path.join(out_dir, "champion_metadata.json")
    if not os.path.exists(path):
        return
    with open(path, "r", encoding="utf-8") as f:
        saved = json.load(f)
    saved_identity = (saved.get("model_version"),
                      saved.get("dataset", {}).get("feature_set_label"))
    if saved_identity != (MODEL_VERSION, FEATURE_SET_LABEL):
        raise SystemExit(
            f"Refusing to overwrite {out_dir}: it holds champion "
            f"{saved_identity}, but config.yaml now describes "
            f"{(MODEL_VERSION, FEATURE_SET_LABEL)}. Point "
            "model_governance.artifacts_dir at a new folder for a new champion."
        )


def main() -> None:
    import argparse
    global XGB_PARAMS_SOURCE
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--pin-xgboost-params", metavar="METADATA_JSON",
        help="Fix XGBoost hyperparameters to the best_params in this "
             "champion_metadata.json instead of grid-searching them.",
    )
    parser.add_argument(
        "--no-prompt", action="store_true",
        help="Do not ask whether to run evaluate_models.py at the end "
             "(for non-interactive runs).",
    )
    args = parser.parse_args()

    print("=" * 58)
    print("SENTINEL CREDIT — BASELINE MODEL TRAINING")
    print("=" * 58)

    refuse_foreign_package(ARTIFACTS_DIR)
    if args.pin_xgboost_params:
        best = pin_xgboost_params(args.pin_xgboost_params)
        XGB_PARAMS_SOURCE = os.path.relpath(args.pin_xgboost_params, PROJECT_ROOT)
        print(f"XGBoost hyperparameters PINNED from {XGB_PARAMS_SOURCE}: {best}")

    df = load_data()
    print(f"Loaded {len(df):,} modelable customers, "
          f"{len(MODEL_FEATURES)} features")

    mlflow.set_tracking_uri(MLFLOW_TRACKING_URI)
    mlflow.set_experiment(MLFLOW_EXPERIMENT)
    print(f"\nMLflow experiment: {MLFLOW_EXPERIMENT}")
    print(f"  feature_set tag:      {FEATURE_SET_LABEL}")
    print(f"  pipeline_stage:       {PIPELINE_STAGE}")
    print(f"  dataset_version:      {DATASET_VERSION}")
    print(f"  model_version tag:    {MODEL_VERSION}")
    print(f"  git_commit tag:       {get_git_commit()}")
    print(f"  decision_log_version: {DECISION_LOG_VERSION}")
    print(f"  data_end_date:        {CONFIG['data_generator']['data_end_date']}")
    print("  View with: mlflow ui  (then http://localhost:5000)")

    out_dir = ARTIFACTS_DIR
    os.makedirs(out_dir, exist_ok=True)

    all_results = {}

    for strategy in ["stratified", "temporal"]:
        print(f"\n{'=' * 58}")
        print(f"SPLIT STRATEGY: {strategy}")
        print("=" * 58)

        if strategy == "temporal" and not MODEL_CFG.get("temporal_split_date"):
            print(f"  Skipped — split_strategy: temporal requires "
                  f"model.temporal_split_date in config.yaml")
            continue

        X_train, X_test, y_train, y_test, ids_train, ids_test = split_data(df, strategy)

        print(f"Train bad rate {y_train.mean():.2%}  "
              f"Test bad rate {y_test.mean():.2%}")

        # AUC/Gini are undefined with only one target class in
        # the test set. Shouldn't occur under the current
        # full-observation horizon; if it does, investigate the
        # split or feature-store population.
        if y_test.nunique() < 2:
            print(
                "  SKIPPED — test set contains only one target class "
                f"({int(y_test.sum())}/{len(y_test)} positive). "
                "Review the temporal split date and regenerated "
                "feature-store population."
            )
            continue

        results = []
        for train_fn in [train_logistic_regression, train_decision_tree, train_xgboost]:
            print(f"\nTraining {train_fn.__name__}...")
            result = train_fn(X_train, y_train, X_test, y_test)
            log_to_mlflow(result, X_train, y_train, strategy)
            results.append(result)
            print(f"  Gini: {result['gini']:.4f}  AUC: {result['auc']:.4f}")

        print_summary(results)
        all_results[strategy] = results

        # Saved per strategy, so evaluate_models.py can be
        # pointed at either.
        eval_frame = X_test.copy()
        eval_frame["customer_id"] = ids_test.values
        eval_frame[TARGET_COLUMN] = y_test.values
        for r in results:
            eval_frame[f"proba_{r['name']}"] = r["test_proba"]
        out_path = os.path.join(out_dir, f"test_predictions_{strategy}.csv")
        eval_frame.to_csv(out_path, index=False)
        print(f"\nTest predictions saved to {out_path}")

        # Governed model package persisted only for the
        # canonical split (stratified) — the split every
        # downstream decision and document is based on.
        if strategy == "stratified":
            save_model_package(
                results, X_train, y_train, X_test, y_test,
                ids_train, ids_test, strategy, out_dir,
            )

    if len(all_results) == 2:
        print_split_comparison(all_results)

    completed_splits = list(all_results.keys())
    if not completed_splits:
        print("\nNo split completed successfully — nothing to evaluate.")
        return

    print(f"\nCompleted split(s): {', '.join(completed_splits)}")
    answer = "n" if args.no_prompt else input(
        "Run evaluate_models.py now for these split(s)? [y/n]: "
    ).strip().lower()

    if answer == "y":
        script_dir = os.path.dirname(os.path.abspath(__file__))
        for split in completed_splits:
            print(f"\nRunning evaluate_models.py --split {split} ...\n")
            subprocess.run(
                [sys.executable, os.path.join(script_dir, "evaluate_models.py"),
                 "--split", split],
                check=False,
            )
    else:
        print("\nRun manually when ready, e.g.:")
        for split in completed_splits:
            print(f"  python models\\evaluate_models.py --split {split}")


if __name__ == "__main__":
    main()
